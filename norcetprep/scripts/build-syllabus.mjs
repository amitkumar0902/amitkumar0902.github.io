function slug(s) {
  return s.toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .replace(/--+/g, '-')
    .slice(0, 60);
}

const priorityMap = { m: 'must', s: 'should', n: 'nice' };
const rows = [];

for (const [section, items] of Object.entries(SECTIONS)) {
  items.forEach((item, idx) => {
    const [topic, subtopic, p] = item;
    const id = section + '-' + String(idx + 1) + '-' + slug(topic);
    const override = DAY_OVERRIDES[id];
    rows.push({
      id,
      section,
      sectionLabel: SECTION_LABELS[section],
      topic,
      subtopic: subtopic || null,
      day: override || SECTION_DAY[section],
      priority: priorityMap[p] || 'should',
    });
  });
}

fs.writeFileSync(OUT, JSON.stringify(rows, null, 2));
console.log('Wrote', rows.length, 'syllabus entries →', OUT);

const bySection = {};
const byPriority = { must: 0, should: 0, nice: 0 };
rows.forEach(r => {
  bySection[r.section] = (bySection[r.section] || 0) + 1;
  byPriority[r.priority]++;
});
